/** Regenerates tests/routes.mjs from the planner scripts below (dev tool).
 *  node tests/generate-routes.mjs           # all levels
 *  node tests/generate-routes.mjs 1-3       # print one level's summaries only
 * Each script is a plain sequence of ordinary commands; the output is then
 * re-verified by a from-scratch replay before it is written. */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { Planner, replay } from "./route-planner.mjs";
import { SCRIPTS } from "./route-scripts.mjs";
import * as M from "../model.mjs";

const only = process.argv[2];
const out = {};
for (const [id, scripts] of Object.entries(SCRIPTS)) {
  if (only && id !== only) continue;
  out[id] = {};
  for (const [kind, script] of Object.entries(scripts)) {
    const planner = new Planner(id);
    try {
      script(planner);
    } catch (error) {
      console.error(`${id} ${kind}: ${error.message}`, planner.summary());
      process.exitCode = 1;
      continue;
    }
    const route = planner.route(),
      g = replay(id, route),
      summary = { ...planner.summary(), entries: route.length };
    const same = g.phase === planner.g.phase && Math.abs(g.time - planner.g.time) < 1e-9 && M.stickerCount(g) === M.stickerCount(planner.g);
    console.log(id, kind, JSON.stringify(summary), same ? "replay ok" : "REPLAY MISMATCH");
    if (!same || g.phase !== "won") process.exitCode = 1;
    out[id][kind] = route;
  }
}
if (!only && !process.exitCode) {
  const fmt = (route) => "[\n" + route.map(([s, input]) => `      [${s}, ${JSON.stringify(input)}],`).join("\n") + "\n    ]";
  const body = Object.entries(out)
    .map(([id, r]) => `  "${id}": {\n    baseline: ${fmt(r.baseline)},\n    mastery: ${fmt(r.mastery)},\n  },`)
    .join("\n");
  const file = `/** Ordinary-input fixtures shared by the model tests and the root browser QA.
 * GENERATED by tests/generate-routes.mjs from tests/route-scripts.mjs; edit the
 * scripts, not these numbers.
 *
 * ROUTES[levelId] = { baseline, mastery }. Each route is a JSON array of
 * [seconds, input] entries for M.advance / window.__game.step: pulses (jump,
 * jumpReleased, dash, color) fire on an entry's first 1/120 s tick, left/right
 * are held for the whole entry. No positions are set, no collision is disabled,
 * nothing is teleported. Every route starts from a fresh game of its level
 * (createGame(id) / __game.startLevel(id)) and wins it with zero deaths.
 *
 * baseline = the main line a first-time player is guided along.
 * mastery  = all three of the level's stickers.
 */
export const ROUTES = {
${body}
};
export const LEVEL_ROUTE_IDS = Object.keys(ROUTES);
/** Legacy names kept for the root QA suite: the old single-stage routes are
 * gone; these now point at the World 1 finale (1-6 The Vault), which must be
 * started with __game.startLevel("1-6") before replaying. */
export const BASELINE_ROUTE = ROUTES["1-6"].baseline;
export const MASTERY_ROUTE = ROUTES["1-6"].mastery;
`;
  writeFileSync(fileURLToPath(new URL("./routes.mjs", import.meta.url)), file);
  console.log("wrote tests/routes.mjs");
}
